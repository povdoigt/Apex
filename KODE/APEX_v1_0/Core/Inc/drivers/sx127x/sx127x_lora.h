#define sx127x_LORA_REG_29_FEI_MID					0x29
#define sx127x_LORA_REG_2A_FEI_LSB					0x2a
// REG 2B is reserved
#define sx127x_LORA_REG_2C_RSSI_WIDEBAND			0x2c
