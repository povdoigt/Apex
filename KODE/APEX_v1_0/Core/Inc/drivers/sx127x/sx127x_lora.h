#define sx127x_LORA_REG_1C_HOP_CHANNEL				0x1c
#define sx127x_LORA_REG_1D_MODEM_CONFIG1			0x1d
#define sx127x_LORA_REG_1E_MODEM_CONFIG2			0x1e
#define sx127x_LORA_REG_1F_SYMB_TIMEOUT_LSB			0x1f
