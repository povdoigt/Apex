#define sx127x_LORA_REG_10_FIFO_RX_CURRENT_ADDR		0x10
#define sx127x_LORA_REG_11_IRQ_FLAGS_MSK			0x11
#define sx127x_LORA_REG_12_IRQ_FLAGS				0x12
#define sx127x_LORA_REG_13_RX_NB_BYTES				0x13
